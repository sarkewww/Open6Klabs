#!/usr/bin/env node
/**
 * extract-font-faces.mjs
 *
 * Regenerates `app/src/styles/fonts.css`: the 14 *selectable* font families'
 * `@font-face` rules, copied VERBATIM from the committed `widget/` reference
 * stylesheets, in settings-registry order.
 *
 * Why a curated 14 (not all 37 CSS families)?
 *   `widget/assets/main-Dj8S0xjW.css` declares 817 `@font-face` rules across 37
 *   families, but the widget settings font registry exposes exactly 14 choices
 *   (`.omo/_beautify/useAmuseSettings.js` -> `y`, mirrored by
 *   `app/src/amuse/settings/registry.ts`). This file is the curated subset the
 *   app owns.
 *
 * Sources (byte-for-byte, never edited here):
 *   - Poppins            -> widget/css/critical-fonts.css  (src: /webfonts/poppins/**)
 *   - the other 13       -> widget/assets/main-Dj8S0xjW.css (src: /assets/<family>-*.woff2)
 *
 * Usage:
 *   node tools/extract-font-faces.mjs           # write app/src/styles/fonts.css
 *   node tools/extract-font-faces.mjs --check   # exit 1 if the file is stale
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..');
const MAIN_CSS = join(ROOT, 'widget', 'assets', 'main-Dj8S0xjW.css');
const CRITICAL_CSS = join(ROOT, 'widget', 'css', 'critical-fonts.css');
const OUT = join(ROOT, 'app', 'src', 'styles', 'fonts.css');

/** Settings-registry order (ids) mapped to the real CSS family names. */
const FAMILIES = [
  { id: 'poppins', css: 'Poppins', source: 'critical' },
  { id: 'fredoka', css: 'Fredoka Variable', source: 'main' },
  { id: 'spacemono', css: 'Space Mono', source: 'main' },
  { id: 'silkscreen', css: 'Silkscreen', source: 'main' },
  { id: 'bagelFatOne', css: 'Bagel Fat One', source: 'main' },
  { id: 'gasoekOne', css: 'Gasoek One', source: 'main' },
  { id: 'zcoolKuaile', css: 'ZCOOL KuaiLe', source: 'main' },
  { id: 'zcoolQingkeHuangyou', css: 'ZCOOL QingKe HuangYou', source: 'main' },
  { id: 'singleDay', css: 'Single Day', source: 'main' },
  { id: 'jua', css: 'Jua', source: 'main' },
  { id: 'russoOne', css: 'Russo One', source: 'main' },
  { id: 'monomakh', css: 'Monomakh', source: 'main' },
  { id: 'notoSerifDisplay', css: 'Noto Serif Display Variable', source: 'main' },
  { id: 'openDyslexic', css: 'OpenDyslexic', source: 'main' },
];

/** Extract `@font-face{...}` blocks whose font-family is exactly `family`. */
function blocksFor(css, family) {
  const out = [];
  const re = /@font-face\s*\{([^}]*)\}/g;
  let m;
  while ((m = re.exec(css))) {
    const decl = m[1];
    const fm = decl.match(/font-family\s*:\s*([^;}]+)/);
    if (!fm) continue;
    const name = fm[1].trim().replace(/^["']|["']$/g, '');
    if (name === family) out.push('@font-face{' + decl + '}');
  }
  return out;
}

function build() {
  const main = readFileSync(MAIN_CSS, 'utf8');
  const critical = readFileSync(CRITICAL_CSS, 'utf8');
  const chunks = [];
  const counts = [];
  for (const { id, css, source } of FAMILIES) {
    const src = source === 'critical' ? critical : main;
    const blocks = blocksFor(src, css);
    if (blocks.length === 0) throw new Error(`no @font-face for family "${css}" (${id})`);
    counts.push(`${id}=${blocks.length}`);
    chunks.push(`/* ${id} -> ${css} (${source}) */`, ...blocks);
  }
  const header = [
    '/*',
    ' * app/src/styles/fonts.css',
    ' *',
    ' * The 14 selectable font families (@font-face rules copied VERBATIM from the',
    ' * committed widget/ reference: widget/css/critical-fonts.css for Poppins,',
    ' * widget/assets/main-Dj8S0xjW.css for the other 13).',
    ' *',
    ' * Generated by tools/extract-font-faces.mjs - do not edit by hand.',
    ' * Sources are self-hosted: /assets/<family>-*.woff2 and /webfonts/poppins/**.',
    ' * Registry: .omo/_beautify/useAmuseSettings.js -> `y` (14 fonts).',
    ' */',
    '',
  ].join('\n');
  return { text: header + chunks.join('\n') + '\n', counts, families: FAMILIES.length };
}

const { text, counts, families } = build();

if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (current !== text) {
    console.error('extract-font-faces: app/src/styles/fonts.css is STALE');
    process.exit(1);
  }
  console.log(`extract-font-faces: up to date (${families} families)`);
} else {
  writeFileSync(OUT, text, 'utf8');
  console.log(`extract-font-faces: wrote ${families} families -> app/src/styles/fonts.css`);
  console.log('  ' + counts.join('  '));
}
